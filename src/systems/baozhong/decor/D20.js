// D20 廣告學系：創意廣告提案所。通用幾何獎座，不仿任何獅形商標。
export default function build(ctx) {
  // 提案燈箱有兩根落地腳；暖色內板和便條貼都貼附在面板上。
  ctx.box(0.06, 0.86, 0.16, '#5d4037', -1.02, 0.43, -0.2);
  ctx.box(0.06, 0.86, 0.16, '#5d4037', -0.58, 0.43, -0.2);
  ctx.box(0.7, 0.9, 0.08, '#ff6f00', -0.8, 1.2, -0.2, { out: 0.03 });
  ctx.box(0.59, 0.77, 0.012, '#fff3c4', -0.8, 1.2, -0.15);
  const colors = ['#ef5350', '#42a5f5', '#ffee58', '#81c784', '#ffb74d', '#ce93d8'];
  for (let i = 0; i < 6; i++) {
    ctx.box(0.19, 0.15, 0.012, colors[i], -0.93 + (i % 2) * 0.26, 1.43 - Math.floor(i / 2) * 0.23, -0.138, { rz: i % 2 ? 0.06 : -0.05 });
  }
  // 桌上金色幾何獎座：階梯底座、短柱與四面晶體。
  ctx.box(0.27, 0.055, 0.24, '#5d4037', 0.4, 0.7775, 1.0);
  ctx.box(0.2, 0.065, 0.18, '#ffca28', 0.4, 0.8375, 1.0);
  ctx.cyl(0.035, 0.045, 0.12, '#ffb300', 0.4, 0.93, 1.0, { seg: 6 });
  ctx.cyl(0.08, 0.13, 0.22, '#ffd700', 0.4, 1.1, 1.0, { seg: 4, ry: Math.PI / 4 });
  // 一本橙色文案提案稿，紙張與封面層疊在櫃檯上。
  ctx.box(0.33, 0.035, 0.25, '#e65100', -0.2, 0.7675, 1.0);
  ctx.box(0.29, 0.012, 0.21, '#fff8e1', -0.2, 0.791, 1.0);
  ctx.sign('創意文案策略', { w: 0.9, h: 0.3, bg: '#e65100', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return { hideCanopy: false, hideCounter: false };
}
