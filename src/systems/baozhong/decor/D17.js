/* D17 財務管理學系「公司財務併購室」（Grok，T059／T060／T061；照攤位佈景 D20＋E20＋F20）
   左後方現金流折現漏斗（F20：倒錐改 ctx.cyl(0.25,0.03,0.45)，兩腳支架＋橫桿撐住）、上方落下的金幣、漏斗下方金幣堆；右後方兩塊互鎖併購拼圖（藍＋綠，藍色凸榫插進綠塊）；櫃檯上財報卷宗與估值計算機，櫃檯正面「現金流折現 DCF」小牌。不寫報酬率承諾、不畫 CFA logo。保留頂棚與櫃檯。 */
export default function build(ctx) {
  const O = { out: 0.03 };
  // 漏斗支架：兩腳（落地照 T061 ＋0.03）＋橫桿
  ctx.box(0.05, 1.0, 0.05, '#5d4037', -1.08, 0.53, -0.3, O);
  ctx.box(0.05, 1.0, 0.05, '#5d4037', -0.52, 0.53, -0.3, O);
  ctx.box(0.6, 0.04, 0.06, '#5d4037', -0.8, 1.05, -0.3, O);
  // 倒錐漏斗（T060 ④：cone 不能倒轉，用 cyl 大上小下）
  ctx.cyl(0.25, 0.03, 0.45, '#ffb300', -0.8, 1.25, -0.3, O);
  // 落入漏斗的現金流金幣
  ctx.cyl(0.07, 0.07, 0.02, '#ffd54f', -0.8, 1.62, -0.3, { rx: 1.2, out: 0.03 });
  ctx.cyl(0.07, 0.07, 0.02, '#ffd54f', -0.72, 1.8, -0.3, { rx: 0.6, out: 0.03 });
  // 漏斗下方金幣堆（落地）
  ctx.cyl(0.1, 0.1, 0.15, '#ffd54f', -0.8, 0.105, -0.3, O);
  // 併購拼圖：藍塊＋綠塊，藍色凸榫插入綠塊
  ctx.box(0.4, 0.6, 0.15, '#1e88e5', 0.55, 0.33, -0.6, O);
  ctx.box(0.4, 0.6, 0.15, '#43a047', 0.97, 0.33, -0.6, O);
  ctx.cyl(0.08, 0.08, 0.15, '#1e88e5', 0.78, 0.33, -0.6, { rx: Math.PI / 2 });
  // 櫃檯上財報卷宗（深藍封面＋白紙）
  ctx.box(0.3, 0.06, 0.22, '#1a237e', -0.3, 0.81, 1.0, O);
  ctx.box(0.27, 0.02, 0.19, '#ffffff', -0.3, 0.85, 1.0);
  // 櫃檯上估值計算機＋液晶
  ctx.box(0.22, 0.05, 0.3, '#424242', 0.35, 0.8, 1.0, O);
  ctx.box(0.16, 0.01, 0.07, '#a5d6a7', 0.35, 0.83, 0.92);
  // 櫃檯正面小牌（第 2 個文字牌）
  ctx.sign('現金流折現 DCF', { w: 0.9, h: 0.2, bg: '#ffffff', fg: '#1a237e', x: 0, y: 0.45, z: 1.32 });
  // 主招牌（T060 ③）
  ctx.sign('資本運作與估值', { w: 1.0, h: 0.3, bg: '#1a237e', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
