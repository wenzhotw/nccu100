// D30 東南亞語文：竹木高腳屋與一般稻穗，不使用東協徽章。
export default function build(ctx) {
  // 四樁從地面支撐屋頂；屋頂最高 1.57，保留原帳篷頂棚。
  for (const x of [-0.95, -0.35]) {
    for (const z of [-0.65, -0.05]) {
      ctx.cyl(0.04, 0.04, 1.4, '#8d6e63', x, 0.7, z);
    }
  }
  ctx.box(0.7, 0.08, 0.7, '#a1887f', -0.65, 0.50, -0.35);
  ctx.box(0.78, 0.09, 0.46, '#b99a50', -0.65, 1.44, -0.55, { rx: -0.25 });
  ctx.box(0.78, 0.09, 0.46, '#b99a50', -0.65, 1.44, -0.15, { rx: 0.25 });
  // 收束底座與三束金色稻穗都由櫃檯承托，不畫圓環或標誌。
  ctx.cyl(0.13, 0.15, 0.06, '#8d6e63', 0.3, 0.78, 1.0);
  ctx.cone(0.075, 0.30, '#ffd54f', 0.20, 0.96, 1.0);
  ctx.cone(0.075, 0.38, '#ffca28', 0.30, 1.00, 1.0);
  ctx.cone(0.075, 0.30, '#ffd54f', 0.40, 0.96, 1.0);
  // 木製指示牌，不另加未審定的多語字樣。
  ctx.box(0.04, 0.5, 0.04, '#5d4037', 0.70, 1.0, 0.95);
  ctx.box(0.42, 0.12, 0.035, '#bcaaa4', 0.70, 1.18, 0.975);
  ctx.sign('ASEAN Languages', { w: 0.9, h: 0.3, bg: '#e65100', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
