/* D13 會計學系「精密審計平衡堂」（Grok，T059／T060／T061；照攤位佈景 D16＋E16＋F16）
   左後方巨型古典木框算盤（5 檔算珠，加兩支落地立架）、櫃檯上借貸平衡雙色柱（藍 Debit、紅 Credit＋平衡橫桿）、紅色印章盒，櫃檯正面「借方 Debit＝貸方 Credit」小牌。不印任何事務所 logo。保留頂棚與櫃檯。 */
export default function build(ctx) {
  const O = { out: 0.03 };
  // 算盤立架（F16：兩支 box 腳到地面；描邊落地照 T061 ＋0.03）
  ctx.box(0.05, 0.9, 0.05, '#4e342e', -1.1, 0.48, -0.2, O);
  ctx.box(0.05, 0.9, 0.05, '#4e342e', -0.5, 0.48, -0.2, O);
  // 算盤木框背板＋中樑
  ctx.box(0.7, 0.4, 0.04, '#d7ccc8', -0.8, 1.13, -0.22, O);
  ctx.box(0.7, 0.03, 0.07, '#5d4037', -0.8, 1.2, -0.19);
  // 5 檔算珠：上珠一顆、下珠一串
  const cols = [-1.04, -0.92, -0.8, -0.68, -0.56];
  for (const x of cols) {
    ctx.cyl(0.045, 0.045, 0.05, '#ff8f00', x, 1.27, -0.17);
    ctx.cyl(0.045, 0.045, 0.16, '#ff8f00', x, 1.04, -0.17);
  }
  // 櫃檯上借貸平衡柱：藍 Debit、紅 Credit，上架平衡橫桿
  ctx.box(0.12, 0.45, 0.12, '#1565c0', 0.5, 1.005, 0.9, O);
  ctx.box(0.12, 0.45, 0.12, '#c62828', 0.68, 1.005, 0.9, O);
  ctx.box(0.36, 0.03, 0.1, '#ffd54f', 0.59, 1.275, 0.9, O);
  // 櫃檯上紅色印章盒
  ctx.box(0.15, 0.08, 0.12, '#c62828', 0.0, 0.82, 1.0, O);
  // 櫃檯正面小牌（第 2 個文字牌）
  ctx.sign('借方 Debit ＝ 貸方 Credit', { w: 0.9, h: 0.2, bg: '#ffffff', fg: '#0d47a1', x: 0, y: 0.45, z: 1.32 });
  // 主招牌（T060 ③）
  ctx.sign('會計系・借貸平衡', { w: 1.0, h: 0.3, bg: '#0d47a1', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
