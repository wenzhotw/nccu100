/* D03 哲學系「愛智沉思坊」（Grok，T059／T060；照攤位佈景 D6＋F6）
   希臘石柱上的沉思者（Rodin, Le Penseur，方塊拼）、寫「正／反／合」的辯證黑板、櫃檯上金色問號。保留頂棚與櫃檯。 */
export default function build(ctx) {
  const O = { out: 0.03 };
  const stone = '#b0bec5';
  // 石柱＋沉思者（F6：灰色 sphere 頭＋box 身，不必寫實）
  ctx.box(0.36, 0.08, 0.36, '#eceff1', -0.9, 0.04, -0.3);          // 柱座
  ctx.cyl(0.12, 0.14, 1.1, '#cfd8dc', -0.9, 0.63, -0.3, O);           // 柱身 0.08~1.18
  ctx.box(0.32, 0.06, 0.32, '#eceff1', -0.9, 1.21, -0.3, O);          // 柱頭 ~1.24
  ctx.box(0.2, 0.26, 0.16, stone, -0.9, 1.37, -0.32, O);              // 身體（坐姿）
  ctx.box(0.2, 0.06, 0.14, stone, -0.9, 1.27, -0.2, O);               // 大腿向前
  ctx.box(0.05, 0.2, 0.05, stone, -0.86, 1.42, -0.2, { rx: -0.5, out: 0.03 }); // 托腮的手臂
  ctx.sphere(0.08, stone, -0.9, 1.56, -0.25, O);                       // 低頭的頭
  // 辯證黑板（落地畫架＋木框＋黑板＋第 2 個文字牌）
  ctx.cyl(0.025, 0.025, 1.5, '#6d4c41', 0.45, 0.75, -0.62);
  ctx.cyl(0.025, 0.025, 1.5, '#6d4c41', 1.05, 0.75, -0.42);
  ctx.box(1.06, 0.61, 0.04, '#8d6e63', 0.75, 1.2, -0.53, { ry: -0.3, out: 0.03 });
  ctx.box(1.0, 0.55, 0.05, '#263238', 0.74, 1.2, -0.5, { ry: -0.3 });
  ctx.box(0.9, 0.03, 0.08, '#8d6e63', 0.73, 0.93, -0.46, { ry: -0.3 }); // 粉筆槽
  ctx.sign('正／反／合', { w: 0.9, h: 0.4, bg: '#263238', fg: '#ffffff', x: 0.731, y: 1.22, z: -0.47, ry: -0.3 });
  // 櫃檯上金色問號（底座＋支桿＋點＋直筆＋彎鉤）
  ctx.box(0.25, 0.04, 0.15, '#5d4037', 0, 0.77, 1.0, O);
  ctx.sphere(0.04, '#fbc02d', 0, 0.83, 1.03, O);
  ctx.cyl(0.012, 0.012, 0.12, '#5d4037', 0, 0.85, 0.96);
  ctx.box(0.05, 0.1, 0.05, '#fbc02d', 0, 0.94, 1.0, O);
  ctx.torus(0.09, 0.025, '#fbc02d', 0, 1.08, 1.0, { arc: Math.PI * 1.5, ry: Math.PI });
  // 主招牌（T060 ③）
  ctx.sign('哲學系・愛智之學', { w: 1.0, h: 0.3, bg: '#4e342e', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
