// 範例（Claude，T060）：照通則①至⑤寫的最小佈景，給 Grok、GPT 參考，不對應任何系。
export default function build(ctx) {
  const c = ctx.color;
  // 櫃檯上的茶壺：底在 0.75（通則①）
  ctx.sphere(0.12, '#8d6e63', 0.3, 0.75 + 0.12, 1.0, { out: 0.03 });
  ctx.cyl(0.02, 0.03, 0.12, '#8d6e63', 0.45, 0.9, 1.0, { rz: -0.9 });
  // 落地的展示架：y = 高/2；兩腳加板子，不懸空
  ctx.box(0.05, 1.2, 0.05, '#5d4037', -0.95, 0.6, -0.4);
  ctx.box(0.05, 1.2, 0.05, '#5d4037', -0.45, 0.6, -0.4);
  ctx.box(0.6, 0.45, 0.04, c, -0.7, 1.0, -0.4, { out: 0.03 });
  // 倒錐用 cyl（通則④）
  ctx.cyl(0.18, 0.02, 0.3, '#ffb300', 0.8, 0.15 + 0.03, -0.6, { out: 0.03 });  // 有描邊的落地物要再抬高 out
  // 閃爍燈只切 visible（通則⑤）
  const led = ctx.sphere(0.04, '#00e676', -0.7, 1.3, -0.38);
  // 主招牌在頂棚上方（通則③）
  ctx.sign('範例攤位', { w: 1.0, h: 0.3, bg: c, fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  let t = 0;
  return { update(dt) { t += dt; led.visible = (t % 1) < 0.5; } };
}
