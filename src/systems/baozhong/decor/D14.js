/* D14 統計學系「高斯大數據實驗室」（Grok，T059／T060／T061；照攤位佈景 D17＋E17＋F17）
   左後方高低錯落四階長條圖柱、右後方 9 根小柱依常態分配高度排成鐘形拱（F17：不用自訂曲面）、櫃檯上迴歸分析散佈圖立板（4 個資料點＋紅色迴歸線）。保留頂棚與櫃檯。 */
export default function build(ctx) {
  const O = { out: 0.03 };
  // 左後方長條圖四階柱（落地，描邊＋0.03）
  const bars = [[-1.2, 0.3, '#a5d6a7'], [-1.02, 0.6, '#66bb6a'], [-0.84, 0.9, '#2e7d32'], [-0.66, 0.5, '#81c784']];
  for (const [x, h, c] of bars) ctx.box(0.15, h, 0.15, c, x, h / 2 + 0.03, -0.3, O);
  // 右後方常態分配鐘形拱：9 根柱，高度 0.1＋1.2·exp(−k²/(2·1.5²))
  for (let i = 0; i < 9; i++) {
    const k = i - 4;
    const h = Math.round((0.1 + 1.2 * Math.exp(-(k * k) / 4.5)) * 1000) / 1000;
    ctx.box(0.1, h, 0.12, k === 0 ? '#1565c0' : '#42a5f5', 0.4 + 0.11 * i, h / 2 + 0.03, -0.4, O);
  }
  // 櫃檯上迴歸分析散佈圖立板＋資料點＋迴歸線
  ctx.box(0.5, 0.35, 0.03, '#fffde7', 0.35, 0.955, 1.0, O);
  const pts = [[0.17, 0.85], [0.29, 0.92], [0.41, 1.0], [0.53, 1.08]];
  for (const [x, y] of pts) ctx.box(0.04, 0.04, 0.02, '#1b5e20', x, y + (x === 0.29 ? 0.03 : 0), 1.025);
  ctx.box(0.46, 0.015, 0.01, '#d32f2f', 0.35, 0.965, 1.035, { rz: 0.57 });
  // 主招牌（T060 ③）
  ctx.sign('統計系・統計與大數據', { w: 1.0, h: 0.3, bg: '#1b5e20', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
