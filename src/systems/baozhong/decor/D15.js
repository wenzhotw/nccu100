/* D15 企業管理學系「商業個案圓桌會」（Grok，T059／T060／T061；照攤位佈景 D18＋E18＋F18）
   左後方三層企業組織金字塔（落地，頂端金色領導者球）、右後方 Porter 五力分析盤（F18：扁 cyl 立起＋5 色小 box，中央同業競爭，上下左右為新進者、替代品、供應商、買方；落地支架）、櫃檯上黑色公事包。不印真實企業 logo。保留頂棚與櫃檯。 */
export default function build(ctx) {
  const O = { out: 0.03 };
  // 組織金字塔三層（落地，描邊＋0.03）
  ctx.box(0.6, 0.35, 0.6, '#90caf9', -0.8, 0.205, -0.2, O);
  ctx.box(0.42, 0.35, 0.42, '#64b5f6', -0.8, 0.555, -0.2, O);
  ctx.box(0.24, 0.35, 0.24, '#1e88e5', -0.8, 0.905, -0.2, O);
  ctx.sphere(0.08, '#ffd54f', -0.8, 1.19, -0.2, O);
  // 五力分析盤：底座＋立柱＋立起的扁圓盤
  ctx.box(0.3, 0.04, 0.3, '#455a64', 0.85, 0.05, -0.3, O);
  ctx.box(0.06, 1.0, 0.06, '#607d8b', 0.85, 0.57, -0.3, O);
  ctx.cyl(0.35, 0.35, 0.05, '#eceff1', 0.85, 1.35, -0.3, { rx: Math.PI / 2, seg: 16, out: 0.03 });
  // 五力：中央同業競爭、上新進者、下替代品、左供應商、右買方
  const forces = [[0.85, 1.35, '#e53935'], [0.85, 1.56, '#fb8c00'], [0.85, 1.14, '#8e24aa'], [0.64, 1.35, '#43a047'], [1.06, 1.35, '#1e88e5']];
  for (const [x, y, c] of forces) ctx.box(0.12, 0.12, 0.03, c, x, y, -0.24);
  // 櫃檯上黑色公事包＋提把＋金扣
  ctx.box(0.35, 0.25, 0.12, '#212121', 0.3, 0.905, 1.0, O);
  ctx.torus(0.06, 0.015, '#212121', 0.3, 1.06, 1.0, { arc: Math.PI });
  ctx.box(0.05, 0.03, 0.01, '#ffd54f', 0.3, 0.97, 1.065);
  // 主招牌（T060 ③）
  ctx.sign('企管系・全方位管理', { w: 1.0, h: 0.3, bg: '#d48806', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
