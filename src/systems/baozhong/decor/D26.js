// D26 日本語文學系：桜の茶屋。鳥居位置依 F 欄，最高處低於頂棚。
export default function build(ctx) {
  ctx.cyl(0.05, 0.05, 1.50, '#ce3830', -0.85, 0.765, 0.3, { out: 0.015 });
  ctx.cyl(0.05, 0.05, 1.50, '#ce3830', 0.85, 0.765, 0.3, { out: 0.015 });
  ctx.box(1.90, 0.075, 0.085, '#c8322d', 0, 1.30, 0.3, { out: 0.012 });
  ctx.box(2.00, 0.08, 0.13, '#9c2b28', 0, 1.56, 0.3, { out: 0.012 });
  ctx.box(2.00, 0.08, 0.19, '#282c32', 0, 1.66, 0.3, { out: 0.012 });

  // 稻草色注連繩在貫下，由短繩連到貫；四片白紙垂而非紅白幕。
  ctx.cyl(0.025, 0.025, 1.55, '#ccb484', 0, 1.19, 0.35, { rz: Math.PI / 2 });
  ctx.cyl(0.012, 0.012, 0.12, '#ccb484', -0.70, 1.25, 0.35);
  ctx.cyl(0.012, 0.012, 0.12, '#ccb484', 0.70, 1.25, 0.35);
  for (let i = 0; i < 4; i++) {
    ctx.box(0.065, 0.16, 0.012, '#fffdf4', -0.54 + i * 0.36, 1.105, 0.36,
      { rz: i % 2 ? -0.18 : 0.18, out: 0.004 });
  }

  // 茶碗、茶湯與茶筅均由桌面或茶托承托。
  ctx.cyl(0.12, 0.12, 0.025, '#b78b59', 0.26, 0.7675, 1.0, { out: 0.005 });
  ctx.cyl(0.085, 0.06, 0.08, '#557941', 0.26, 0.825, 1.0, { out: 0.008 });
  ctx.cyl(0.071, 0.071, 0.008, '#81984c', 0.26, 0.866, 1.0);
  ctx.cyl(0.025, 0.055, 0.12, '#e6cc8b', 0.57, 0.81, 1.0, { seg: 12 });
  ctx.cyl(0.018, 0.025, 0.12, '#bb9250', 0.57, 0.93, 1.0);
  ctx.sign('桜の茶屋', { w: 0.8, h: 0.3, bg: '#c2185b', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return { hideCanopy: false, hideCounter: false };
}
