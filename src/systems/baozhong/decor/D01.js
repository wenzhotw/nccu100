/* D01 中國文學系「水墨書卷閣」（Grok，T059／T060；照攤位佈景 D4＋F4）
   巨型毛筆立在硯台上、櫃檯上竹簡與線裝書、紅色落款印章、後方山水掛軸。保留頂棚與櫃檯。 */
export default function build(ctx) {
  const O = { out: 0.03 };
  // 巨型毛筆（F4：筆桿不傾斜，與筆頭同軸；筆頭用倒錐 cyl）
  ctx.box(0.5, 0.04, 0.5, '#212121', -0.9, 0.02, 0);            // 硯台（墨池）
  ctx.cyl(0.07, 0.015, 0.3, '#ffffff', -0.9, 0.19, 0, O);          // 筆頭白毛 0.04~0.34
  ctx.cyl(0.04, 0.02, 1.8, '#5d4037', -0.9, 1.1, 0, O);            // 筆桿 0.2~2.0
  ctx.cyl(0.05, 0.05, 0.08, '#b71c1c', -0.9, 0.36, 0, O);          // 筆桿與筆頭接口
  // 櫃檯上：竹簡（底 0.75）
  ctx.box(0.5, 0.04, 0.3, '#c8a165', -0.35, 0.77, 1.0, O);
  ctx.box(0.04, 0.05, 0.31, '#5d4037', -0.5, 0.775, 1.0);          // 編繩
  ctx.box(0.04, 0.05, 0.31, '#5d4037', -0.2, 0.775, 1.0);
  // 線裝書兩本
  ctx.box(0.3, 0.05, 0.22, '#1a237e', 0.1, 0.775, 1.0, O);
  ctx.box(0.28, 0.05, 0.2, '#283593', 0.1, 0.825, 1.0, { ry: 0.15, out: 0.03 });
  // 紅色落款方章（D4）＋章鈕
  ctx.box(0.12, 0.12, 0.12, '#b71c1c', 0.5, 0.81, 1.0, O);
  ctx.cyl(0.03, 0.03, 0.06, '#7f0000', 0.5, 0.9, 1.0);
  // 後方山水掛軸（不寫假書法，只畫山水＋紅印）
  ctx.cyl(0.025, 0.025, 1.9, '#5d4037', -0.45, 0.95, -1.2);     // 立架
  ctx.cyl(0.025, 0.025, 1.9, '#5d4037', 0.45, 0.95, -1.2);
  ctx.cyl(0.03, 0.03, 1.0, '#5d4037', 0, 1.85, -1.2, { rz: Math.PI / 2 });   // 橫桿
  ctx.box(0.7, 1.2, 0.02, '#fafafa', 0, 1.2, -1.2, O);             // 畫心 0.6~1.8
  ctx.cyl(0.03, 0.03, 0.8, '#5d4037', 0, 0.6, -1.19, { rz: Math.PI / 2 });   // 下軸
  ctx.cone(0.18, 0.4, '#546e7a', -0.1, 0.9, -1.16, O);              // 遠山
  ctx.cone(0.13, 0.3, '#90a4ae', 0.15, 0.85, -1.15, O);
  ctx.box(0.06, 0.06, 0.01, '#c62828', 0.22, 1.6, -1.185);          // 畫上紅印
  // 主招牌（T060 ③）
  ctx.sign('中文系・文以載道', { w: 1.0, h: 0.3, bg: '#800020', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
