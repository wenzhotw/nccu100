/* D16 資訊管理學系「雲端資料庫樞紐」（Grok，T059／T060／T061；照攤位佈景 D19＋E19＋F19）
   左後方三層關聯資料庫圓筒（藍色＋淺藍頂蓋）、右後方伺服器機櫃（兩顆 LED 輪流亮，照 T061 只切 visible）、櫃檯上筆記型電腦模型，櫃檯正面 ER 圖小牌（學生─選課─課程）。不寫亂碼假程式。保留頂棚與櫃檯。 */
export default function build(ctx) {
  const O = { out: 0.03 };
  // 關聯資料庫圓筒三層（落地照 T061 ＋0.03）＋淺藍頂蓋
  const ys = [0.17, 0.48, 0.79];
  for (const y of ys) {
    ctx.cyl(0.22, 0.22, 0.28, '#0277bd', -0.8, y, -0.4, O);
    ctx.cyl(0.2, 0.2, 0.02, '#4fc3f7', -0.8, y + 0.15, -0.4);
  }
  // 伺服器機櫃＋兩條硬碟槽
  ctx.box(0.45, 1.5, 0.4, '#37474f', 0.75, 0.78, -0.6, O);
  ctx.box(0.36, 0.05, 0.02, '#90a4ae', 0.75, 0.75, -0.39);
  ctx.box(0.36, 0.05, 0.02, '#90a4ae', 0.75, 0.95, -0.39);
  // LED 兩顆輪流亮（T061 ⑤：只切 mesh.visible，update 內不 new）
  const ledA = ctx.box(0.07, 0.07, 0.02, '#00e676', 0.65, 1.3, -0.39);
  const ledB = ctx.box(0.07, 0.07, 0.02, '#ffea00', 0.85, 1.3, -0.39);
  // 櫃檯上筆記型電腦：底座、螢幕外框、亮面
  ctx.box(0.4, 0.03, 0.28, '#cfd8dc', 0.3, 0.78, 1.0, O);
  ctx.box(0.4, 0.26, 0.02, '#263238', 0.3, 0.93, 0.86, O);
  ctx.box(0.34, 0.2, 0.005, '#4fc3f7', 0.3, 0.93, 0.875);
  // 櫃檯正面 ER 圖小牌（第 2 個文字牌）
  ctx.sign('ER 圖：學生 ─ 選課 ─ 課程', { w: 0.9, h: 0.2, bg: '#ffffff', fg: '#01579b', x: 0, y: 0.45, z: 1.32 });
  // 主招牌（T060 ③）
  ctx.sign('商業與資訊架構', { w: 1.0, h: 0.3, bg: '#01579b', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  let t = 0;
  return {
    update(dt) {
      t += dt;
      const on = (t % 1) < 0.5;
      ledA.visible = on;
      ledB.visible = !on;
    }
  };
}
