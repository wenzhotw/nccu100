// D21 廣播電視學系：獨立電影片場。拍板有支架，導演椅保留開放椅腳。
export default function build(ctx) {
  // 黑白拍板架：兩腳落地，拍板與條紋上板均由支架承托。
  ctx.box(0.055, 1.18, 0.09, '#455a64', -0.99, 0.59, -0.2);
  ctx.box(0.055, 1.18, 0.09, '#455a64', -0.61, 0.59, -0.2);
  ctx.box(0.56, 0.36, 0.045, '#212121', -0.8, 1.0, -0.17, { out: 0.02 });
  ctx.box(0.56, 0.085, 0.05, '#212121', -0.8, 1.24, -0.17, { rz: 0.12 });
  for (let i = 0; i < 3; i++) {
    const x = -0.98 + i * 0.18;
    ctx.box(0.085, 0.075, 0.008, '#fffdf4', x, 1.24 + (x + 0.8) * 0.12, -0.142, { rz: -0.35 });
  }
  // 雙膠捲盤的下緣落在 0.75 櫃檯面，輪軸固定在盤面。
  ctx.cyl(0.25, 0.25, 0.055, '#90a4ae', 0.8, 1.0, 0.8, { rx: Math.PI / 2, seg: 12 });
  ctx.cyl(0.25, 0.25, 0.055, '#cfd8dc', 0.8, 1.0, 0.94, { rx: Math.PI / 2, seg: 12 });
  ctx.cyl(0.075, 0.075, 0.21, '#263238', 0.8, 1.0, 0.89, { rx: Math.PI / 2 });
  // 盤面交叉槽與中央輪軸形成可辨識的四瓣膠捲輪。
  ctx.box(0.055, 0.34, 0.006, '#263238', 0.8, 1.0, 0.9705, { rz: Math.PI / 4 });
  ctx.box(0.055, 0.34, 0.006, '#263238', 0.8, 1.0, 0.9705, { rz: -Math.PI / 4 });
  ctx.box(0.36, 0.04, 0.26, '#fff8e1', -0.22, 0.77, 1.0);
  // 導演帆布椅：後腳延伸到椅背，六件組件都有接觸面。
  ctx.box(0.4, 0.06, 0.36, '#7b1fa2', 0.2, 0.52, -0.73);
  ctx.box(0.4, 0.26, 0.045, '#7b1fa2', 0.2, 0.84, -0.88);
  ctx.box(0.045, 0.52, 0.045, '#6d4c41', 0.03, 0.26, -0.58);
  ctx.box(0.045, 0.52, 0.045, '#6d4c41', 0.37, 0.26, -0.58);
  ctx.box(0.045, 0.97, 0.045, '#6d4c41', 0.03, 0.485, -0.88);
  ctx.box(0.045, 0.97, 0.045, '#6d4c41', 0.37, 0.485, -0.88);
  ctx.sign('獨立專題影展', { w: 0.9, h: 0.3, bg: '#7b1fa2', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return { hideCanopy: false, hideCounter: false };
}
