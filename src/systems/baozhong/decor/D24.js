// D24 阿拉伯語文學系：綠洲市集。T060/T061，採用已審 C/D/F。
// 阿拉伯文須由 Claude 在實際 Chromium 檢查連寫與缺字；本檔不代表字型驗收通過。
export default function build(ctx) {
  // Dallah：壺身底含描邊恰在櫃檯 0.75，長嘴與把手接在壺身。
  ctx.cyl(0.08, 0.12, 0.45, '#e9b82e', -0.8, 0.99, 0.9, { out: 0.015 });
  ctx.cone(0.10, 0.10, '#ffd965', -0.8, 1.26, 0.9, { out: 0.01 });
  ctx.sphere(0.025, '#8d6e30', -0.8, 1.33, 0.9);
  ctx.cyl(0.024, 0.036, 0.28, '#e9b82e', -0.64, 1.07, 0.9, { rz: -0.8 });
  ctx.cyl(0.017, 0.024, 0.17, '#ffd965', -0.50, 1.20, 0.9, { rz: -0.65 });
  ctx.torus(0.105, 0.018, '#c79425', -0.93, 1.04, 0.9);

  // 兩個交疊正方形形成八角星，落地立架承托，沒有宗教文字。
  ctx.box(0.52, 0.07, 0.32, '#6d4c41', 0.15, 0.05, -0.35, { out: 0.015 });
  ctx.box(0.065, 1.10, 0.065, '#6d4c41', 0.15, 0.62, -0.38, { out: 0.015 });
  ctx.box(0.38, 0.38, 0.05, '#e7bd57', 0.15, 1.18, -0.33, { out: 0.012 });
  ctx.box(0.38, 0.38, 0.05, '#008577', 0.15, 1.18, -0.30, { rz: Math.PI / 4, out: 0.012 });

  // 椰棗盤與三顆低多邊形點心，全部承托於櫃檯。
  ctx.box(0.38, 0.035, 0.25, '#a97646', 0.35, 0.7775, 1.0, { out: 0.01 });
  for (let i = 0; i < 3; i++) {
    const date = ctx.sphere(0.045, '#6d3427', 0.25 + i * 0.10, 0.83, 1.0);
    date.scale.set(0.75, 0.65, 1.1);
  }

  // 綠洲棕櫚盆景：盆落地，樹幹接盆，三片交錯葉形成六向樹冠。
  ctx.cyl(0.14, 0.115, 0.25, '#bc6b46', 0.85, 0.14, -0.55, { out: 0.015 });
  ctx.cyl(0.022, 0.032, 0.60, '#98643a', 0.85, 0.56, -0.55);
  for (let i = 0; i < 3; i++) {
    ctx.box(0.55, 0.035, 0.09, i === 1 ? '#388e3c' : '#467b3a', 0.85, 0.875, -0.55,
      { ry: i * Math.PI / 3, rz: 0.10 });
  }
  ctx.sign('اللغة العربية', { w: 0.9, h: 0.3, bg: '#00695c', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return { hideCanopy: false, hideCounter: false };
}
