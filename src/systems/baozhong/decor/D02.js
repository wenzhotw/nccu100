/* D02 歷史學系「時光考古閣」（Grok，T059／T060；照攤位佈景 D5＋F5）
   青銅方鼎（四腳、雙耳、金色紋帶）、櫃檯上泛黃卷軸、平放的考古放大鏡、後方年代時間軸看板。保留頂棚與櫃檯。 */
export default function build(ctx) {
  const O = { out: 0.03 };
  // 青銅方鼎（F5：4 腳 cyl(0.04,0.04,0.2) y=0.1；鼎身 y 0.4，底 0.2 接腳）
  for (const [x, z] of [[-1.05, -0.35], [-0.55, -0.35], [-1.05, -0.05], [-0.55, -0.05]]) {
    ctx.cyl(0.04, 0.04, 0.2, '#004d40', x, 0.1, z);
  }
  ctx.box(0.6, 0.4, 0.4, '#00695c', -0.8, 0.4, -0.2, O);
  ctx.box(0.62, 0.07, 0.42, '#c9a227', -0.8, 0.5, -0.2);           // 饕餮紋帶（金）
  ctx.torus(0.08, 0.02, '#004d40', -1.0, 0.6, -0.2, { arc: Math.PI }); // 鼎耳
  ctx.torus(0.08, 0.02, '#004d40', -0.6, 0.6, -0.2, { arc: Math.PI });
  // 櫃檯上：泛黃卷軸（橫放，底 0.75）
  ctx.cyl(0.05, 0.05, 0.7, '#d7ccc8', -0.2, 0.8, 1.0, { rz: Math.PI / 2, out: 0.03 });
  // 考古放大鏡：平放在櫃檯上（鏡框＋鏡片＋握把）
  ctx.torus(0.15, 0.02, '#d4af37', 0.4, 0.77, 1.0, { rx: Math.PI / 2 });
  ctx.cyl(0.14, 0.14, 0.01, '#b3e5fc', 0.4, 0.765, 1.0);
  ctx.box(0.2, 0.03, 0.04, '#5d4037', 0.65, 0.77, 1.0, O);
  // 後方年代時間軸看板（落地兩柱）
  ctx.cyl(0.03, 0.03, 1.75, '#5d4037', -0.9, 0.875, -1.3);
  ctx.cyl(0.03, 0.03, 1.75, '#5d4037', 0.9, 0.875, -1.3);
  ctx.box(2.0, 0.5, 0.05, '#efebe9', 0, 1.5, -1.3, O);
  ctx.box(1.8, 0.03, 0.02, '#5d4037', 0, 1.5, -1.27);                // 時間軸線
  ctx.sphere(0.06, '#00695c', -0.6, 1.5, -1.26, O);                   // 年代節點
  ctx.sphere(0.06, '#c9a227', 0, 1.5, -1.26, O);
  ctx.sphere(0.06, '#b71c1c', 0.6, 1.5, -1.26, O);
  // 主招牌（T060 ③）
  ctx.sign('歷史系・鑑往知來', { w: 1.0, h: 0.3, bg: '#5d4037', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
