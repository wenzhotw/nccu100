// D33 心理：雙半球大腦、潘洛斯三角框與眼動儀；不混稱三角階梯。
export default function build(ctx) {
  // 大腦中心 x=-0.5、y=0.93；兩個壓扁半球由櫃檯承托。
  const left = ctx.sphere(0.18, '#f8bbd0', -0.59, 0.93, 1.0);
  const right = ctx.sphere(0.18, '#f48fb1', -0.41, 0.93, 1.0);
  left.scale.set(0.68, 1.0, 0.85);
  right.scale.set(0.68, 1.0, 0.85);
  // 三根方柱形成三角框，支架接住底邊；不增加樓梯或漂浮部件。
  ctx.box(0.34, 0.07, 0.25, '#78909c', 0.65, 0.035, -0.4);
  ctx.box(0.055, 0.81, 0.055, '#78909c', 0.65, 0.475, -0.4);
  ctx.box(0.60, 0.06, 0.06, '#8e24aa', 0.65, 0.91, -0.4);
  ctx.box(0.06, 0.60, 0.06, '#ab47bc', 0.50, 1.17, -0.4, { rz: -Math.PI / 6 });
  ctx.box(0.06, 0.60, 0.06, '#ce93d8', 0.80, 1.17, -0.4, { rz: Math.PI / 6 });
  // 眼動儀前方兩枚感測窗，不額外使用文字牌。
  ctx.box(0.25, 0.15, 0.2, '#455a64', 0.2, 0.825, 1.0);
  ctx.box(0.065, 0.04, 0.015, '#80deea', 0.14, 0.835, 1.1075);
  ctx.box(0.065, 0.04, 0.015, '#80deea', 0.26, 0.835, 1.1075);
  ctx.sign('心智與大腦科學', { w: 0.9, h: 0.3, bg: '#6a1b9a', fg: '#ffffff', x: 0, y: 3.25, z: 0 });
  return {};
}
